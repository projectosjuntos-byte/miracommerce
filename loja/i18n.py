def translate_text(value, language='pt-pt'):
    if not value or not language or not language.startswith('en'):
        return value
    return TRANSLATIONS.get(value, value)


def translate_html(content, language='pt-pt'):
    if not language or not language.startswith('en'):
        return content
    translated = content
    for source, target in sorted(TRANSLATIONS.items(), key=lambda item: len(item[0]), reverse=True):
        translated = translated.replace(source, target)
    return translated
